import { test } from "node:test";
import assert from "node:assert/strict";
import { ALGORITHMS } from "../src/algorithms.ts";

// msfa's routing table (google/music-synthesizer-for-android, app/src/main/jni/fm_core.cc, Apache-2.0), used here
// only as an independent check of our transcription. One byte per operator, OP6 first, run in that order:
// bits 0–1 output bus (0 = the output, i.e. a carrier), bit 2 add to the bus (else replace it), bits 4–5 input bus,
// bit 6 feedback in, bit 7 feedback out.
const MSFA = [
  [0xc1, 0x11, 0x11, 0x14, 0x01, 0x14], [0x01, 0x11, 0x11, 0x14, 0xc1, 0x14], [0xc1, 0x11, 0x14, 0x01, 0x11, 0x14],
  [0x41, 0x11, 0x94, 0x01, 0x11, 0x14], [0xc1, 0x14, 0x01, 0x14, 0x01, 0x14], [0x41, 0x94, 0x01, 0x14, 0x01, 0x14],
  [0xc1, 0x11, 0x05, 0x14, 0x01, 0x14], [0x01, 0x11, 0xc5, 0x14, 0x01, 0x14], [0x01, 0x11, 0x05, 0x14, 0xc1, 0x14],
  [0x01, 0x05, 0x14, 0xc1, 0x11, 0x14], [0xc1, 0x05, 0x14, 0x01, 0x11, 0x14], [0x01, 0x05, 0x05, 0x14, 0xc1, 0x14],
  [0xc1, 0x05, 0x05, 0x14, 0x01, 0x14], [0xc1, 0x05, 0x11, 0x14, 0x01, 0x14], [0x01, 0x05, 0x11, 0x14, 0xc1, 0x14],
  [0xc1, 0x11, 0x02, 0x25, 0x05, 0x14], [0x01, 0x11, 0x02, 0x25, 0xc5, 0x14], [0x01, 0x11, 0x11, 0xc5, 0x05, 0x14],
  [0xc1, 0x14, 0x14, 0x01, 0x11, 0x14], [0x01, 0x05, 0x14, 0xc1, 0x14, 0x14], [0x01, 0x14, 0x14, 0xc1, 0x14, 0x14],
  [0xc1, 0x14, 0x14, 0x14, 0x01, 0x14], [0xc1, 0x14, 0x14, 0x01, 0x14, 0x04], [0xc1, 0x14, 0x14, 0x14, 0x04, 0x04],
  [0xc1, 0x14, 0x14, 0x04, 0x04, 0x04], [0xc1, 0x05, 0x14, 0x01, 0x14, 0x04], [0x01, 0x05, 0x14, 0xc1, 0x14, 0x04],
  [0x04, 0xc1, 0x11, 0x14, 0x01, 0x14], [0xc1, 0x14, 0x01, 0x14, 0x04, 0x04], [0x04, 0xc1, 0x11, 0x14, 0x04, 0x04],
  [0xc1, 0x14, 0x04, 0x04, 0x04, 0x04], [0xc4, 0x04, 0x04, 0x04, 0x04, 0x04],
];

// Run msfa's buses symbolically: which operators end up in each bus, and so who modulates whom.
function fromMsfa(flags: number[]) {
  const bus: Record<number, number[]> = { 1: [], 2: [] };
  const carriers: number[] = [], edges: string[] = [];
  let fbIn = 0, fbOut = 0;
  flags.forEach((f, i) => {
    const op = 6 - i;
    const inBus = (f >> 4) & 3, outBus = f & 3, add = (f & 4) !== 0;
    if (inBus) for (const m of bus[inBus]!) edges.push(`${m}>${op}`);
    if (f & 0x40) fbIn = op;
    if (f & 0x80) fbOut = op;
    if (outBus === 0) carriers.push(op);
    else bus[outBus] = add ? [...bus[outBus]!, op] : [op];
  });
  return { carriers: carriers.sort(), edges: edges.sort(), feedback: [fbOut, fbIn] };
}

test("32 algorithms, each matching msfa's routing", () => {
  assert.equal(ALGORITHMS.length, 32);
  ALGORITHMS.forEach((a, i) => {
    const m = fromMsfa(MSFA[i]!);
    assert.deepEqual([...a.carriers].sort(), m.carriers, `algorithm ${i + 1} carriers`);
    assert.deepEqual(a.edges.map(([f, t]) => `${f}>${t}`).sort(), m.edges, `algorithm ${i + 1} modulation`);
    assert.deepEqual([...a.feedback], m.feedback, `algorithm ${i + 1} feedback`);
  });
});

test("every operator is used, and only modulators feed others", () => {
  for (const a of ALGORITHMS) {
    const ops = new Set([...a.carriers, ...a.edges.flat()]);
    assert.equal(ops.size, 6);
    for (const [from] of a.edges) assert.ok(!a.carriers.includes(from), "a carrier is never a modulator");
  }
});
